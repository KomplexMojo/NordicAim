// REV-163: the frame every coach image shares (analysis.md §5, patterns.md §7, goals.md §9): the dark header with the title,
// the filters and the time it was made, and the wordmark; and the foot with the athlete line and the credit. Pure SVG.

import { appNameWordmark, brandMotif } from './brand-mark';
import { DEVELOPER_NAME, FOOTER_APP_NAME, provenanceLine } from './composite';
import { PALETTE } from './palette';
import { el, text } from './svg';

export const COACH_WIDTH = 1440;
export const COACH_HEADER_HEIGHT = 120;
export const COACH_FOOTER_HEIGHT = 110;

/** The header: `title` large, `subtitle` (the filters and the time) under it, the mark and wordmark on the right. */
export function coachHeader(title: string, subtitle: string): string {
  const bg = el('rect', { x: 0, y: 0, width: COACH_WIDTH, height: COACH_HEADER_HEIGHT, fill: PALETTE.header });
  const heading = text(40, 58, 36, title, { bold: true, color: '#FFFFFF' });
  const sub = text(40, 94, 18, subtitle, { color: '#CFE6F3' });
  const mark = brandMotif(COACH_WIDTH - 40 - 76, 22, 76);
  const name = appNameWordmark(COACH_WIDTH - 40 - 76 - 14, 71, 34, '#FFFFFF');
  return bg + heading + sub + name + mark;
}

/** The foot at `y`: REV-100's athlete line (when there is one) and the credit. */
export function coachFooter(y: number, provenance: { name: string; club: string; stamp: string | null } | undefined, release: string): string {
  let out = el('rect', { x: 0, y, width: COACH_WIDTH, height: COACH_FOOTER_HEIGHT, fill: PALETTE.panel });
  if (provenance !== undefined) {
    const line = provenanceLine(provenance);
    if (line !== '') out += text(40, y + 40, 20, line, { bold: true, color: PALETTE.textPrimary });
  }
  out += text(40, y + 78, 14, `Generated by ${FOOTER_APP_NAME} created by ${DEVELOPER_NAME} release ${release}`, {
    color: PALETTE.textSecondary,
  });
  return out;
}

/** The whole image: a full-canvas panel first (a transparent area renders black), then `body`. */
export function coachSvg(height: number, body: string): string {
  const bg = el('rect', { x: 0, y: 0, width: COACH_WIDTH, height, fill: PALETTE.panel });
  return el('svg', { xmlns: 'http://www.w3.org/2000/svg', width: COACH_WIDTH, height, viewBox: `0 0 ${COACH_WIDTH} ${height}` }, bg + body);
}
